/**
 * The licence line at the top of every source file of the code (LICENSING.md, part 1): two
 * lines in the file's own comment syntax, after a shebang if there is one.
 *
 *   node scripts/spdx-headers.ts          lists the files without it, and fails if any
 *   node scripts/spdx-headers.ts --fix    adds it to them
 *
 * scripts/spdx-headers.test.ts runs the check with the unit tests, so a new file without the
 * header fails `pnpm test`, `pnpm gate` and CI. Files under another licence, generated or
 * copied from others, and data are left alone (OUTSIDE below).
 */
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

export const ROOT = join(import.meta.dirname, "..");

export const SPDX_LINE = "SPDX-License-Identifier: AGPL-3.0-or-later";
export const TERMS_LINE = "Additional terms under section 7: see LICENSING.md";

/** The comment syntax of a file the header goes in, by its extension; undefined: none. */
function syntaxOf(path: string): "slash" | "block" | "hash" | undefined {
  if (/\.(?:ts|tsx|mts|cts|js|mjs|cjs)$/.test(path)) return "slash";
  if (path.endsWith(".css")) return "block";
  if (/\.(?:py|sh)$/.test(path)) return "hash";
  // The workflows only: the other YAML files are data, templates or configuration of others.
  if (/^\.github\/workflows\/[^/]+\.ya?ml$/.test(path)) return "hash";
  return undefined;
}

/**
 * Paths that keep no AGPL header: the articles and the data (content/, their own licences),
 * the places-in-any-text script (MIT, with its own header; the released copies stay byte for
 * byte as published), and the files a script generates.
 */
const OUTSIDE: readonly RegExp[] = [
  /^content\//,
  /^apps\/web\/public\/hg-places(?:-[^/]*)?\.js$/,
  /^apps\/web\/public\/[a-z]{2}\//,
  /^apps\/web\/public\/(?:data|api|docs)\//,
  // Generated by pipeline/build_versification.py from the World English Bible.
  /^packages\/model\/src\/versification\.ts$/,
  /^scripts\/fixtures\//,
];

/** The header as the file's syntax writes it. */
export function headerFor(syntax: "slash" | "block" | "hash"): string {
  if (syntax === "slash") return `// ${SPDX_LINE}\n// ${TERMS_LINE}\n`;
  if (syntax === "hash") return `# ${SPDX_LINE}\n# ${TERMS_LINE}\n`;
  return `/* ${SPDX_LINE}\n   ${TERMS_LINE} */\n`;
}

/** The files the header belongs in: the code in git, by its extension, less OUTSIDE. */
export function headedFiles(root = ROOT): string[] {
  const listed = execFileSync(
    "git",
    ["ls-files", "-z", "--cached", "--others", "--exclude-standard"],
    {
      cwd: root,
      encoding: "utf8",
    },
  )
    .split("\0")
    .filter(Boolean);
  return [...new Set(listed)]
    .filter((p) => syntaxOf(p) && !OUTSIDE.some((re) => re.test(p)))
    .sort();
}

/** Whether the text opens with the header (after a shebang). */
export function hasHeader(text: string, syntax: "slash" | "block" | "hash"): boolean {
  const body = text.startsWith("#!") ? text.slice(text.indexOf("\n") + 1) : text;
  return body.startsWith(headerFor(syntax));
}

/** The text with the header put in: after a shebang, before the rest, a blank line between. */
export function withHeader(text: string, syntax: "slash" | "block" | "hash"): string {
  if (hasHeader(text, syntax)) return text;
  let shebang = "";
  let body = text;
  if (text.startsWith("#!")) {
    const nl = text.indexOf("\n") + 1;
    shebang = text.slice(0, nl);
    body = text.slice(nl);
  }
  return `${shebang}${headerFor(syntax)}\n${body.replace(/^\n+/, "")}`;
}

/** The files that lack the header. */
export function missingHeaders(root = ROOT): string[] {
  return headedFiles(root).filter((p) => {
    const syntax = syntaxOf(p);
    return syntax !== undefined && !hasHeader(readFileSync(join(root, p), "utf8"), syntax);
  });
}

if (import.meta.main) {
  const missing = missingHeaders();
  if (process.argv.includes("--fix")) {
    for (const p of missing) {
      const syntax = syntaxOf(p);
      if (!syntax) continue;
      const file = join(ROOT, p);
      writeFileSync(file, withHeader(readFileSync(file, "utf8"), syntax));
    }
    console.log(`spdx-headers: added the header to ${String(missing.length)} files`);
  } else if (missing.length) {
    console.error(
      `spdx-headers: ${String(missing.length)} files lack the licence header (node scripts/spdx-headers.ts --fix):\n` +
        missing.map((p) => `  ${p}`).join("\n"),
    );
    process.exitCode = 1;
  } else {
    console.log(`spdx-headers: all ${String(headedFiles().length)} files carry the header`);
  }
}
